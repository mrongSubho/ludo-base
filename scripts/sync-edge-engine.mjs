/**
 * Copy pure engine to Edge shared folder.
 * Run: node scripts/sync-edge-engine.mjs
 * CI compares hashes so app and Edge cannot drift.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'lib/engine/core.ts');
const destDir = join(root, 'supabase/functions/_shared');
const dest = join(destDir, 'engine.ts');

const body = readFileSync(src, 'utf8');
const banner = `// AUTO-GENERATED by scripts/sync-edge-engine.mjs — do not edit.\n// Source: lib/engine/core.ts\n`;
mkdirSync(destDir, { recursive: true });
writeFileSync(dest, banner + body);

const h = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');
const srcH = createHash('sha256').update(body).digest('hex');
const destH = createHash('sha256').update(banner + body).digest('hex');
console.log('synced engine →', dest.replace(root + '/', ''));
console.log('src sha256', srcH.slice(0, 16));
console.log('dest sha256', destH.slice(0, 16));

if (!existsSync(dest)) process.exit(1);
