/**
 * Generate the Edge-side copies of the proof helpers.
 *
 * The client (lib/matchProof.ts, lib/boardLayout.ts) and the Edge functions must
 * produce byte-identical output or a legitimate signature will not verify. Two
 * hand-maintained copies of a digest function drift silently — the failure mode
 * is a match that cannot start, with no useful error. Generated, and gated.
 *
 *   node scripts/sync-edge-proof.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const read = (p) => readFileSync(join(root, p), 'utf8');
const write = (p, s) => writeFileSync(join(root, p), s);

/** Slice from a marker comment to the end of the file. */
function fromMarker(src, marker) {
    return src.slice(src.indexOf(marker));
}

/** Slice an exported function plus its preceding doc comment. */
function exported(src, name) {
    const i = src.indexOf(`export function ${name}`);
    if (i === -1) throw new Error(`${name} not found`);
    const doc = src.lastIndexOf('/**', i);
    let start = doc === -1 ? i : src.lastIndexOf('\n\n', 0, doc);
    start = start === -1 ? 0 : start + 2;
    let depth = 0;
    let k = src.indexOf('{', i);
    for (;;) {
        if (src[k] === '{') depth++;
        else if (src[k] === '}') {
            depth--;
            if (depth === 0) break;
        }
        k++;
    }
    return src.slice(start, k + 1);
}

const proof = read('lib/matchProof.ts');
write(
    'supabase/functions/_shared/boardDigest.ts',
    '// AUTO-GENERATED by scripts/sync-edge-proof.mjs — do not edit.\n' +
        '// Source: lib/matchProof.ts (SEC-16 board digest helpers)\n' +
        '// Client counterpart: lib/matchProof.ts. Both must produce the same digest.\n\n' +
        fromMarker(proof, '/**\n * SEC-16: canonical JSON.'),
);

const layout = read('lib/boardLayout.ts');
write(
    'supabase/functions/_shared/corners.ts',
    '// AUTO-GENERATED by scripts/sync-edge-proof.mjs — do not edit.\n' +
        '// Source: lib/boardLayout.ts (SEC-16 colour assignment)\n' +
        '// Used to reject a color_corner that does not match the declared mode.\n\n' +
        "import type { ColorCorner, Corner } from './engine.ts';\n\n" +
        [exported(layout, 'assignCorners2v2'), exported(layout, 'assignCornersFFA')].join('\n\n') +
        '\n',
);

console.log('synced proof helpers → supabase/functions/_shared/{boardDigest,corners}.ts');
