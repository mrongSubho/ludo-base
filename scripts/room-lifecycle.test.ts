class LifecycleMockWebSocket {
  public readyState = 1;
  public messages: string[] = [];
  private attachment: unknown = null;
  send(data: string) {
    this.messages.push(data);
  }
  close() {
    this.readyState = 3;
  }
  serializeAttachment(att: unknown) {
    this.attachment = att;
  }
  deserializeAttachment() {
    return this.attachment;
  }
  getLastMessage(): Record<string, unknown> | null {
    if (this.messages.length === 0) return null;
    return JSON.parse(this.messages[this.messages.length - 1]);
  }
  getAllMessages(): Array<Record<string, unknown>> {
    return this.messages.map((m) => JSON.parse(m) as Record<string, unknown>);
  }
}

describe('Phase 4 — Match Room Clock, Lifecycle, and Relocation', () => {
  // ── 1. Engine Parity Between App and Room Targets ─────────────────────────
  it('P4-1: pure engine is byte-for-byte identical across app and room targets (Edge copy retired in P6)', () => {
    const root = process.cwd();
    const banner = `// AUTO-GENERATED by scripts/sync-edge-engine.mjs — do not edit.\n// Source: lib/engine/core.ts\n`;
    const appEngine = readFileSync(join(root, 'lib/engine/core.ts'), 'utf8');
    const roomEngine = readFileSync(join(root, 'src/room/engine.ts'), 'utf8');

    assert.equal(roomEngine, banner + appEngine, 'Room engine must match app engine');
  });

  // ── 2. AI Turns via Deterministic lcg32 Seed ───────────────────────────────
  it('P4-2: AI turn decisions are deterministic per (matchId, turn_seq) using lcg32', () => {
    const matchId = '00000000-0000-0000-0000-000000000042';
    const turnSeq = 7;

    // Deterministic seed derivation from matchId + turnSeq
    const deriveSeed = (id: string, seq: number): number => {
      let hash = 0;
      const str = `${id}:${seq}`;
      for (let i = 0; i < str.length; i++) {
        hash = (Math.imul(31, hash) + str.charCodeAt(i)) | 0;
      }
      return hash >>> 0;
    };

    const seedA = deriveSeed(matchId, turnSeq);
    const rngA = lcg32(seedA);
    const drawA1 = rngA();
    const drawA2 = rngA();

    // Replay with identical matchId and turnSeq
    const seedB = deriveSeed(matchId, turnSeq);
    const rngB = lcg32(seedB);
    const drawB1 = rngB();
    const drawB2 = rngB();

    assert.equal(drawA1, drawB1, 'Draw 1 must match exactly');
    assert.equal(drawA2, drawB2, 'Draw 2 must match exactly');

    // Different turnSeq produces distinct seed and stream
    const seedC = deriveSeed(matchId, turnSeq + 1);
    const rngC = lcg32(seedC);
    assert.notEqual(rngC(), drawA1, 'Different turn seq must produce distinct draw');
  });

  // ── 3. match_commit_action Atomic CAS Contract & S0 Seed Persistence ────────
  it('P4-3 / S0: match_commit_action enforces atomic CAS, supports initial seed insertion, and rejects stale seq', () => {
    // Model atomic CAS behavior of match_commit_action including S0 initial seed insertion
    let dbExists = false;
    let dbSeq = 0;
    let dbState = { currentPlayer: 'green', winner: null };
    const eventLog: Array<{ eventType: string; seq: number }> = [];

    const matchCommitAction = (
      expectedSeq: number,
      newState: typeof dbState,
      eventType: string = 'move_committed'
    ) => {
      if (!dbExists) {
        if (expectedSeq <= 0) {
          dbExists = true;
          dbSeq = 0;
          dbState = newState;
          eventLog.push({ eventType, seq: 0 });
          return { ok: true, seq: 0, state: dbState };
        }
        return { ok: false, error: 'MATCH_NOT_FOUND' };
      }

      if (dbSeq !== expectedSeq) {
        return {
          ok: false,
          error: 'STALE_SEQ',
          current_seq: dbSeq,
          state: dbState,
        };
      }
      dbSeq++;
      dbState = newState;
      eventLog.push({ eventType, seq: dbSeq });
      return {
        ok: true,
        seq: dbSeq,
        state: dbState,
      };
    };

    // 0. S0: Initial match seed with expectedSeq = 0 creates match_states row
    const res0 = matchCommitAction(0, { currentPlayer: 'green', winner: null }, 'match_seeded');
    assert.equal(res0.ok, true);
    assert.equal(res0.seq, 0);
    assert.equal(eventLog[0].eventType, 'match_seeded');

    // 1. Move with expectedSeq = 0 succeeds and bumps to seq 1
    const res1 = matchCommitAction(0, { currentPlayer: 'yellow', winner: null }, 'move_committed');
    assert.equal(res1.ok, true);
    assert.equal(res1.seq, 1);
    assert.equal(eventLog.length, 2);
    assert.equal(eventLog[1].eventType, 'move_committed');

    // 2. Concurrent/replayed move with old expectedSeq = 0 fails with STALE_SEQ
    const res2 = matchCommitAction(0, { currentPlayer: 'red', winner: null });
    assert.equal(res2.ok, false);
    assert.equal(res2.error, 'STALE_SEQ');
    assert.equal(res2.current_seq, 1);

    // 3. Sequential move with fresh expectedSeq = 1 succeeds
    const res3 = matchCommitAction(1, { currentPlayer: 'blue', winner: null });
    assert.equal(res3.ok, true);
    assert.equal(res3.seq, 2);
  });

  // ── 4. Wave 2: Phased Turn Clock, Trust, Strikes 1-3 & Dead-Match Refund ───
  it('P4-4: MatchRoomCore enforces 12s cast / 15s move clocks, bidirectional trust, 3-strike kick, spectator redaction, and 30s abort refund RPC', async (t) => {
    const matchId = '99999999-4444-3333-2222-111111111111';
    const walletG = '0x1111111111111111111111111111111111111111';
    const walletY = '0x2222222222222222222222222222222222222222';
    const walletSpec = '0x9999999999999999999999999999999999999999';
    const ticketG = 'wave2-ticket-green';
    const ticketY = 'wave2-ticket-yellow';
    const ticketSpec = 'wave2-ticket-spec';
    const [hashG, hashY, hashSpec] = await Promise.all([
      hashToken(ticketG),
      hashToken(ticketY),
      hashToken(ticketSpec),
    ]);

    const refundCalls: string[] = [];
    const commitEvents: Array<{ eventType: string; payload: Record<string, unknown> }> = [];
    const originalFetch = globalThis.fetch;

    globalThis.fetch = async (input: string | URL | Request, init?: RequestInit): Promise<Response> => {
      const url = typeof input === 'string' ? input : input instanceof URL ? input.toString() : input.url;
      if (url.includes('/rest/v1/sessions')) {
        if (url.includes(hashG)) {
          return new Response(JSON.stringify([{ wallet_address: walletG, scope: 'match', match_id: matchId, seat_color: 'green', expires_at: null, idle_expires_at: null }]), { status: 200, headers: { 'Content-Type': 'application/json' } });
        }
        if (url.includes(hashY)) {
          return new Response(JSON.stringify([{ wallet_address: walletY, scope: 'match', match_id: matchId, seat_color: 'yellow', expires_at: null, idle_expires_at: null }]), { status: 200, headers: { 'Content-Type': 'application/json' } });
        }
        if (url.includes(hashSpec)) {
          return new Response(JSON.stringify([{ wallet_address: walletSpec, scope: 'spectator', match_id: matchId, seat_color: null, expires_at: null, idle_expires_at: null }]), { status: 200, headers: { 'Content-Type': 'application/json' } });
        }
        return new Response(JSON.stringify([]), { status: 200, headers: { 'Content-Type': 'application/json' } });
      }
      if (url.includes('/rest/v1/rpc/match_commit_action')) {
        const body = init?.body ? JSON.parse(String(init.body)) as { p_event_type?: string; p_event_payload?: Record<string, unknown>; p_expected_seq?: number } : {};
        commitEvents.push({
          eventType: String(body.p_event_type || 'unknown'),
          payload: body.p_event_payload || {},
        });
        return new Response(JSON.stringify({ ok: true, seq: (body.p_expected_seq ?? 0) + 1 }), { status: 200, headers: { 'Content-Type': 'application/json' } });
      }
      if (url.includes('/rest/v1/rpc/arena_vault_refund_match')) {
        const body = init?.body ? JSON.parse(String(init.body)) as { p_match_id?: string } : {};
        if (body.p_match_id) refundCalls.push(body.p_match_id);
        return new Response(JSON.stringify({ refunded: true, refunded_count: 2 }), { status: 200, headers: { 'Content-Type': 'application/json' } });
      }
      return new Response('Not found', { status: 404 });
    };

    t.mock.timers.enable({ apis: ['Date'] });
    t.mock.timers.tick(1_000_000);

    try {
      const storageMap = new Map<string, unknown>();
      let connectedSockets: LifecycleMockWebSocket[] = [];
      let scheduledAlarmAt: number | null = null;

      const mockCtx = {
        storage: {
          get: async <T = unknown>(k: string) => storageMap.get(k) as T | undefined,
          put: async (k: string, v: unknown) => { storageMap.set(k, v); },
          setAlarm: async (ts: number) => { scheduledAlarmAt = ts; },
          deleteAlarm: async () => { scheduledAlarmAt = null; },
        },
        getWebSockets: () => connectedSockets as unknown as WebSocket[],
        acceptWebSocket: (ws: unknown) => {
          connectedSockets.push(ws as LifecycleMockWebSocket);
        },
      };
      const mockEnv = {
        NEXT_PUBLIC_SUPABASE_URL: 'https://test-supabase.mock',
        SUPABASE_SERVICE_ROLE_KEY: 'test-service-key',
      };

      const room = new MatchRoomCore(mockCtx as never, mockEnv);

      const connectSock = async (ticket: string) => {
        const ws = new LifecycleMockWebSocket();
        (globalThis as unknown as Record<string, unknown>).WebSocketPair = class {
          0 = new LifecycleMockWebSocket();
          1 = ws;
        };
        await room.fetch(new Request(`https://ludobase.com/api/room/${matchId}/ws?ticket=${ticket}`, { headers: { Upgrade: 'websocket' } }));
        return ws;
      };

      const sockG = await connectSock(ticketG);
      const sockY = await connectSock(ticketY);
      const sockSpec = await connectSock(ticketSpec);

      const cc1v1 = assignCornersForShape('1v1');
      const seededBoard: GameState = {
        ...INITIAL_GAME_STATE,
        matchId,
        playerCount: '1v1',
        currentPlayer: 'green',
        gamePhase: 'rolling',
        isStarted: true,
        status: 'playing',
        positions: {
          green: [25, -1, -1, -1],
          yellow: [38, -1, -1, -1],
          blue: [-1, -1, -1, -1],
          red: [-1, -1, -1, -1],
        },
        playerPowers: {
          green: [{ type: 'boost', expiresAt: 9_999_999 }],
          yellow: [{ type: 'nuke', expiresAt: 9_999_999 }],
          blue: [],
          red: [],
        },
        initialBoardConfig: {
          colorCorner: cc1v1,
          players: [
            { name: 'GreenSeat', level: 1, avatar: '1', color: 'green', position: 'bottom-left', isAi: false, walletAddress: walletG },
            { name: 'YellowSeat', level: 1, avatar: '2', color: 'yellow', position: 'top-right', isAi: false, walletAddress: walletY },
          ],
        },
      };

      // 1. Seed & verify 12s cast timer + serverNow + spectator redaction
      await room.webSocketMessage(
        sockG as unknown as WebSocket,
        JSON.stringify({ v: 1, t: 'seed', payload: seededBoard }),
      );
      let state = storageMap.get('state') as GameState;
      assert.equal(state.turnPhaseKind, 'cast');
      assert.equal(state.turnDurationMs, TURN_TIMERS.castMs);
      assert.equal(state.deadlineAt, Date.now() + TURN_TIMERS.castMs);

      const lastG = sockG.getLastMessage();
      assert.equal(typeof lastG?.serverNow, 'number');

      const specStateMsg = sockSpec.getAllMessages().find((m) => m.t === 'state');
      assert.ok(specStateMsg, 'spectator must receive state frame');
      const specPowers = (specStateMsg.state as GameState).playerPowers;
      assert.equal(specPowers.green[0]?.type, undefined, 'spectator must not receive unmasked power type');
      assert.equal(specPowers.yellow[0]?.type, undefined, 'spectator must not receive unmasked yellow power type');

      await room.webSocketMessage(
        sockSpec as unknown as WebSocket,
        JSON.stringify({ v: 1, t: 'intent', kind: 'REQUEST_ROLL', intentId: 'spec-roll-block' }),
      );
      assert.equal(sockSpec.getLastMessage()?.code, 'NOT_AUTHORIZED');

      // 2. REQUEST_ROLL transitions cast (12s) -> move (15s)
      await room.webSocketMessage(
        sockG as unknown as WebSocket,
        JSON.stringify({ v: 1, t: 'intent', kind: 'REQUEST_ROLL', intentId: 'roll-phase-check' }),
      );
      state = storageMap.get('state') as GameState;
      assert.equal(state.gamePhase, 'moving');
      assert.equal(state.turnPhaseKind, 'move');
      assert.equal(state.turnDurationMs, TURN_TIMERS.moveMs);
      assert.equal(state.deadlineAt, Date.now() + TURN_TIMERS.moveMs);

      // 3. Manual autopilot toggle (CMD_REQUEST_TRUST { trust: true }) is disabled
      await room.webSocketMessage(
        sockG as unknown as WebSocket,
        JSON.stringify({ v: 1, t: 'intent', kind: 'CMD_REQUEST_TRUST', intentId: 'trust-engage', payload: { trust: true } }),
      );
      assert.equal(sockG.getLastMessage()?.code, 'AUTOPILOT_MANUAL_DISABLED');
      state = storageMap.get('state') as GameState;
      assert.equal(state.afkStats.green.isAutoPlaying, false);

      // Move turns until Yellow is active human caster
      const playGreenUntilYellow = async (tag: string) => {
        let loops = 0;
        while ((storageMap.get('state') as GameState).currentPlayer === 'green' && loops < 40) {
          loops++;
          const cur = storageMap.get('state') as GameState;
          if (cur.gamePhase === 'rolling') {
            await room.webSocketMessage(sockG as unknown as WebSocket, JSON.stringify({ v: 1, t: 'intent', kind: 'REQUEST_ROLL', intentId: `${tag}-r-${loops}` }));
          } else {
            const rollSteps = cur.diceValue ?? 1;
            const legalIdx = cur.positions.green.findIndex(
              (pos) => calculateNextPosition(pos, rollSteps, 'green', cc1v1) !== pos,
            );
            await room.webSocketMessage(
              sockG as unknown as WebSocket,
              JSON.stringify({ v: 1, t: 'intent', kind: 'REQUEST_MOVE', intentId: `${tag}-m-${loops}`, payload: { tokenIndex: legalIdx >= 0 ? legalIdx : 0 } }),
            );
          }
        }
      };

      await playGreenUntilYellow('init');
      assert.equal((storageMap.get('state') as GameState).currentPlayer, 'yellow');

      // 4. Dual-tier AFK lifecycle: triggers 1..4 enter reclaimable Tier-1, trigger 5/5 permanently kicks
      for (let triggerNum = 1; triggerNum <= AFK_MAX_TRIGGERS; triggerNum++) {
        // Ensure it is Yellow's human turn cleanly
        await playGreenUntilYellow(`cyc-${triggerNum}`);
        if ((storageMap.get('state') as GameState).currentPlayer === 'yellow') {
          t.mock.timers.tick(TURN_TIMERS.castMs + 50);
          await room.alarm();

          // Complete Yellow's two-phase bot move if Yellow rolled a valid move
          let botSafety = 0;
          while (
            (storageMap.get('state') as GameState).currentPlayer === 'yellow' &&
            botSafety < 10
          ) {
            botSafety++;
            const curTimers = (storageMap.get('timerHeap') as Array<{ kind: string; deadlineAt: number }>) || [];
            const turnTm = curTimers.find((tm) => tm.kind === 'ai_roll' || tm.kind === 'ai_move');
            assert.ok(turnTm, 'bot turn uses staggered ai_roll / ai_move alarm');
            if (turnTm.kind === 'ai_roll') {
              const delta = turnTm.deadlineAt - Date.now();
              assert.ok(delta >= AFK_BOT_ROLL_DELAY_MS.min - 50 && delta <= AFK_BOT_ROLL_DELAY_MS.max + 50);
            } else {
              const delta = turnTm.deadlineAt - Date.now();
              assert.ok(delta >= AFK_BOT_MOVE_DELAY_MS.min - 50 && delta <= AFK_BOT_MOVE_DELAY_MS.max + 50);
            }
            t.mock.timers.tick(Math.max(10, turnTm.deadlineAt - Date.now() + 20));
            await room.alarm();
          }
        }

        state = storageMap.get('state') as GameState;
        assert.equal(state.afkStats.yellow.afkTriggers, triggerNum, `trigger ${triggerNum}/5 recorded`);

        if (triggerNum < AFK_MAX_TRIGGERS) {
          assert.equal(state.afkStats.yellow.isAutoPlaying, true);
          assert.equal(state.afkStats.yellow.isKicked, false);
          assert.ok(typeof state.afkStats.yellow.afkDeadlineAt === 'number');

          // Yellow taps anywhere / sends reclaim before deadline
          await room.webSocketMessage(
            sockY as unknown as WebSocket,
            JSON.stringify({ v: 1, t: 'intent', kind: 'CMD_REQUEST_TRUST', intentId: `reclaim-${triggerNum}`, payload: { trust: false } }),
          );
          state = storageMap.get('state') as GameState;
          assert.equal(state.afkStats.yellow.isAutoPlaying, false);
          assert.equal(state.afkStats.yellow.afkTriggers, triggerNum, 'lifetime AFK triggers preserved across reclaim');
        } else {
          assert.equal(state.afkStats.yellow.isKicked, true, '5/5 triggers immediately permanently kicks seat');
          assert.equal(state.afkStats.yellow.kickReason, 'afk_limit_5');
        }
      }

      await room.webSocketMessage(
        sockY as unknown as WebSocket,
        JSON.stringify({ v: 1, t: 'intent', kind: 'CMD_REQUEST_TRUST', intentId: 'reclaim-after-kick', payload: { trust: false } }),
      );
      assert.equal(sockY.getLastMessage()?.code, 'SEAT_KICKED', 'kicked seat hard-locked on wire');

      // 5. 30s dead-match abort SLO + ArenaVault refund RPC
      await room.webSocketClose(sockY as unknown as WebSocket, 1000, 'bye');
      connectedSockets = connectedSockets.filter((s) => s !== sockY);
      // One seat (sockG) remains -> dead_match MUST NOT be armed yet
      let timers = (storageMap.get('timerHeap') as Array<{ kind: string; deadlineAt: number }>) || [];
      assert.equal(timers.some((tm) => tm.kind === 'dead_match'), false);

      await room.webSocketClose(sockG as unknown as WebSocket, 1000, 'bye');
      connectedSockets = connectedSockets.filter((s) => s !== sockG);
      timers = (storageMap.get('timerHeap') as Array<{ kind: string; deadlineAt: number }>) || [];
      const deadTimer = timers.find((tm) => tm.kind === 'dead_match');
      assert.ok(deadTimer, 'last seat close arms 30s dead_match timer');
      assert.notEqual(
        (storageMap.get('state') as GameState).deadlineAt,
        deadTimer.deadlineAt,
        'dead_match timer never leaks into UI turn deadlineAt',
      );

      // Seat reconnects -> cancels dead_match
      const sockG2 = await connectSock(ticketG);
      timers = (storageMap.get('timerHeap') as Array<{ kind: string; deadlineAt: number }>) || [];
      assert.equal(timers.some((tm) => tm.kind === 'dead_match'), false, 'seat reconnect cancels dead_match');

      // Disconnect last seat again and expire 30s dead_match SLO
      await room.webSocketClose(sockG2 as unknown as WebSocket, 1000, 'drop');
      connectedSockets = connectedSockets.filter((s) => s !== sockG2);
      t.mock.timers.tick(TURN_TIMERS.maxDullMs + 50);
      await room.alarm();

      const finalState = storageMap.get('state') as GameState;
      assert.equal(finalState.winner, 'aborted');
      assert.equal(finalState.abortReason, 'no_connected_seats_30s');
      assert.equal(scheduledAlarmAt, null);
      assert.deepEqual((storageMap.get('timerHeap') as unknown[]) || [], []);
      assert.deepEqual(refundCalls, [matchId], 'dead_match abort invokes arena_vault_refund_match RPC');
      assert.ok(commitEvents.some((e) => e.eventType === 'match_aborted'));

      // Reconnecting after abort rejects any mutation with MATCH_FINISHED
      const sockLate = await connectSock(ticketG);
      await room.webSocketMessage(
        sockLate as unknown as WebSocket,
        JSON.stringify({ v: 1, t: 'intent', kind: 'REQUEST_ROLL', intentId: 'post-abort-roll' }),
      );
      assert.equal(sockLate.getLastMessage()?.code, 'MATCH_FINISHED');
    } finally {
      t.mock.timers.reset();
      globalThis.fetch = originalFetch;
    }
  });

  // ── 5. D7 Drill: Host Device Killed Mid-Turn ──────────────────────────────
  it('P4-5: D7 Drill — host socket drop mid-turn does not stall match progress', () => {
    interface MockRoom {
      activeSockets: Set<string>;
      currentPlayer: PlayerColor;
      alarmScheduled: boolean;
      alarmDeadline: number;
    }

    const room: MockRoom = {
      activeSockets: new Set(['host-socket-1', 'guest-socket-2']),
      currentPlayer: 'green',
      alarmScheduled: true,
      alarmDeadline: Date.now() + 15000,
    };

    // Host device is suddenly killed (browser closed / process crash)
    room.activeSockets.delete('host-socket-1');
    assert.equal(room.activeSockets.has('host-socket-1'), false);

    // Turn timer continues to run independently on server DO
    assert.equal(room.alarmScheduled, true);

    // Alarm fires on server: advances turn to guest
    const now = room.alarmDeadline + 1;
    if (now >= room.alarmDeadline) {
      room.currentPlayer = getNextPlayer(room.currentPlayer, '2v2');
      room.alarmDeadline = now + 15000;
    }

    // Match advanced to red despite host death!
    assert.equal(room.currentPlayer, 'red');
  });

  // ── 6. Move Legality & Engine Calculation Parity ───────────────────────────
  it('P4-6: calculateNextPosition computes home lane entrance correctly', () => {
    const cc: ColorCorner = {
      green: 'BL',
      yellow: 'BR',
      blue: 'TR',
      red: 'TL',
    };

    // Green starts at 34, gate is at 32 (50 steps), home lane is 52–57
    const atGate = 32;
    const next = calculateNextPosition(atGate, 3, 'green', cc);
    assert.equal(next, 54); // Entered home lane

    // Overshooting past 57 stays in place
    const nearFinish = 56;
    const overRoll = calculateNextPosition(nearFinish, 3, 'green', cc);
    assert.equal(overRoll, 56); // Illegal overshoot
  });

  // ── 7. S5: Room-Authoritative AI & AutoPlay Turn Progression ──────────────
  it('P4-7 / S5: server room DO progresses bot and autoPlaying seats with zero client host dependency', () => {
    interface SimulatedDO {
      state: {
        currentPlayer: PlayerColor;
        playerCount: '1v1';
        afkStats: Partial<Record<PlayerColor, { isAutoPlaying: boolean }>>;
      };
      scheduledKind: 'turn' | 'ai_turn' | null;
      scheduledDelayMs: number;
    }

    const room: SimulatedDO = {
      state: {
        currentPlayer: 'green',
        playerCount: '1v1',
        afkStats: {
          green: { isAutoPlaying: false },
          yellow: { isAutoPlaying: true },
        },
      },
      scheduledKind: null,
      scheduledDelayMs: 0,
    };

    const scheduleTimer = (kind: 'turn' | 'ai_turn', delayMs: number) => {
      room.scheduledKind = kind;
      room.scheduledDelayMs = delayMs;
    };

    const onStateAdvance = (nextPlayer: PlayerColor) => {
      room.state.currentPlayer = nextPlayer;
      if (room.state.afkStats[nextPlayer]?.isAutoPlaying) {
        scheduleTimer('ai_turn', 1000);
      } else {
        scheduleTimer('turn', 15000);
      }
    };

    // Human player (green) gets 15s turn timer
    onStateAdvance('green');
    assert.equal(room.scheduledKind, 'turn');
    assert.equal(room.scheduledDelayMs, 15000);

    // Turn passes to autoPlaying player (yellow): gets 1s ai_turn alarm
    onStateAdvance('yellow');
    assert.equal(room.scheduledKind, 'ai_turn');
    assert.equal(room.scheduledDelayMs, 1000);
  });
});
