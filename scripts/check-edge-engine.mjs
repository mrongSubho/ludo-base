/**
 * Fail if Edge engine copy drifted from lib/engine/core.ts.
 * Run: node scripts/check-edge-engine.mjs
 */
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'lib/engine/core.ts'), 'utf8');
const dest = readFileSync(join(root, 'supabase/functions/_shared/engine.ts'), 'utf8');
const banner = `// AUTO-GENERATED by scripts/sync-edge-engine.mjs — do not edit.\n// Source: lib/engine/core.ts\n`;

const expected = banner + src;
if (dest !== expected) {
  console.error('❌ Edge engine out of sync. Run: node scripts/sync-edge-engine.mjs');
  process.exit(1);
}
console.log('✓ Edge engine in sync with lib/engine/core.ts');
